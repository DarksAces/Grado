            _chkLow.Location = new Point(100, 12);
            _chkLow.CheckedChanged += (s, e) => ApplyFilter();

            _grid.Location = new Point(10, 40);
            _grid.Size = new Size(660, 360);
            _grid.AutoGenerateColumns = false;
            _grid.AllowUserToAddRows = false;
